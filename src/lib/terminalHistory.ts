import { writeStoredJson } from "./storage";

const TERMINAL_HISTORY_STORAGE_KEY = "pitwall-terminal-history";

/**
 * How much scrollback is worth keeping, and why it is far less than it looks.
 *
 * localStorage is a single ~5MB budget shared with the projects, the tasks and
 * every setting, and it stores UTF-16 — so each character costs two bytes and a
 * character limit is twice as expensive as it reads.
 *
 * These were 200k and 2M, which is 4MB: four fifths of everything available,
 * spent on scrollback. The write is guarded and quietly kept its old value when
 * it hit the ceiling, while the unguarded writes around it threw — so the app
 * held on to the terminal output and lost the projects. Somebody re-added their
 * projects on every launch because of this.
 *
 * 250k characters is 500KB, a tenth of the budget, and still hundreds of lines
 * per session. Scrollback can be regenerated by scrolling. Projects cannot.
 */
export const MAX_SESSION_CHARACTERS = 50_000;
export const MAX_TOTAL_CHARACTERS = 250_000;

const ESC = "\u001b";

/**
 * Clears every text attribute. Restored output always begins mid-stream — the
 * start of the session was trimmed away — so whatever escape sequence last set
 * a colour is gone while its effect is not. Without this the replay inherits
 * that state and paints solid blocks of it across the pane.
 */
export const TERMINAL_REPLAY_RESET = `${ESC}[0m`;

/** Index just past the end of the escape sequence beginning at `start`. */
function escapeSequenceEnd(text: string, start: number): number {
  const introducer = text[start + 1];
  if (introducer === "[") {
    let index = start + 2;
    // CSI runs until its final byte, which is the first character in @-~.
    while (index < text.length && !(text[index] >= "@" && text[index] <= "~")) index += 1;
    return index + 1;
  }
  if (introducer === "]") {
    // OSC ends at BEL or at ST.
    const bell = text.indexOf("\u0007", start);
    const terminator = text.indexOf(`${ESC}\\`, start + 1);
    if (bell !== -1 && (terminator === -1 || bell < terminator)) return bell + 1;
    if (terminator !== -1) return terminator + 2;
    return text.length;
  }
  return start + 2;
}

/**
 * Takes the tail of a chunk without starting inside an escape sequence. A cut
 * landing mid-sequence turns the remainder into literal junk like "31m" and
 * leaves the terminal in whatever state the missing half described — which is
 * how a restored pane ends up painted a solid colour. The partial sequence is
 * dropped rather than guessed at; the replay reset restores a clean slate.
 */
export function trimChunkTail(chunk: string, limit: number) {
  if (chunk.length <= limit) return chunk;
  let start = chunk.length - limit;
  const opener = chunk.lastIndexOf(ESC, start);
  if (opener !== -1) {
    const end = escapeSequenceEnd(chunk, opener);
    // The cut fell inside this sequence, so begin after it instead.
    if (end > start) start = end;
  }
  // JavaScript string indices count UTF-16 units, not characters, so a cut can
  // land between the two halves of an astral character — an emoji, most often.
  // The surviving half is a lone surrogate: not text, and rendered as a broken
  // glyph for the rest of the replay. Step past it.
  const first = chunk.charCodeAt(start);
  if (first >= 0xdc00 && first <= 0xdfff) start += 1;
  return chunk.slice(start);
}

export function trimTerminalHistory(history: Record<string, string[]>) {
  const trimmed: Record<string, string[]> = {};
  let remainingTotal = MAX_TOTAL_CHARACTERS;

  for (const [sessionId, chunks] of Object.entries(history).reverse()) {
    if (remainingTotal <= 0 || !Array.isArray(chunks)) break;
    let remainingSession = Math.min(MAX_SESSION_CHARACTERS, remainingTotal);
    const kept: string[] = [];

    for (let index = chunks.length - 1; index >= 0 && remainingSession > 0; index -= 1) {
      const chunk = String(chunks[index] ?? "");
      if (!chunk) continue;
      const tail = trimChunkTail(chunk, remainingSession);
      kept.unshift(tail);
      remainingSession -= tail.length;
      remainingTotal -= tail.length;
    }

    if (kept.length > 0) trimmed[sessionId] = kept;
  }

  return trimmed;
}

export function readTerminalHistory(): Record<string, string[]> {
  if (typeof window === "undefined") return {};
  try {
    const raw = window.localStorage.getItem(TERMINAL_HISTORY_STORAGE_KEY);
    if (!raw) return {};
    const parsed = JSON.parse(raw) as { version?: number; sessions?: Record<string, string[]> };
    if (parsed?.version !== 1 || !parsed.sessions) return {};
    // Every restored session starts with a clean slate: its opening escape
    // sequences were trimmed away long ago, so their effects must not be
    // inherited by whatever survived.
    const restored = trimTerminalHistory(parsed.sessions);
    for (const [sessionId, chunks] of Object.entries(restored)) {
      restored[sessionId] = [TERMINAL_REPLAY_RESET, ...chunks];
    }
    return restored;
  } catch {
    return {};
  }
}

export function writeTerminalHistory(history: Record<string, string[]>) {
  // Through the shared writer so it obeys the same eviction order as everything
  // else — which, for this key, means it is never allowed to make room for
  // itself at the expense of anything that matters more.
  writeStoredJson(TERMINAL_HISTORY_STORAGE_KEY, {
    version: 1,
    sessions: trimTerminalHistory(history),
  });
}

export function formatTerminalTranscript(chunks: string[]) {
  return chunks
    .map((chunk) => (/\u001b|\r|\n/.test(chunk) ? chunk : `${chunk}\r\n`))
    .join("")
    .replace(/\u001b\][^\u0007]*(?:\u0007|\u001b\\)/g, "")
    .replace(/\u001b\[[0-?]*[ -/]*[@-~]/g, "")
    .replace(/\r\n/g, "\n")
    .replace(/\r/g, "")
    .trim();
}
