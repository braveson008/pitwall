/**
 * Collects the licence texts of everything that ships.
 *
 * Braveli is proprietary but stands on MIT and ISC code, and both licences
 * require their notice travel with binaries that include them. That obligation
 * is not satisfied by listing package names — it needs the copyright line and
 * the licence text, which is why this reads them from the tree rather than
 * being written by hand and going stale at the next `npm install`.
 *
 *   node scripts/generate-notices.mjs
 */
import { readFile, writeFile, readdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const pkg = JSON.parse(await readFile(path.join(root, "package.json"), "utf8"));

/**
 * What actually reaches a user's machine: the runtime dependencies, plus
 * Electron itself, which is a devDependency because electron-builder consumes
 * it — and which is nonetheless the largest thing in the bundle.
 */
const shipped = [...Object.keys(pkg.dependencies ?? {}), "electron"].sort();

const LICENCE_FILES = ["LICENSE", "LICENSE.md", "LICENSE.txt", "LICENCE", "license", "LICENSE-MIT"];

/**
 * Packages that declare a licence but omit the file from their tarball.
 *
 * The obligation is to reproduce the licence, not to reproduce whatever the
 * publisher remembered to pack, so the text is taken from a sibling published
 * out of the same repository under the same licence. Each entry records why it
 * is a sound substitution rather than a guess.
 */
const BORROWED_TEXT = {
  // Same repository (xtermjs/xterm.js) and same declared licence as @xterm/xterm,
  // which does ship LICENSE. The headless build simply does not pack it.
  "@xterm/headless": "@xterm/xterm",
};

async function licenceTextFor(name) {
  const dir = path.join(root, "node_modules", name);
  let entries;
  try {
    entries = await readdir(dir);
  } catch {
    return null;
  }
  const match = entries.find((entry) => LICENCE_FILES.includes(entry))
    ?? entries.find((entry) => /^licen[cs]e/i.test(entry));
  if (!match) return null;
  return (await readFile(path.join(dir, match), "utf8")).trim();
}

const sections = [];
const missing = [];

for (const name of shipped) {
  let meta;
  try {
    meta = JSON.parse(await readFile(path.join(root, "node_modules", name, "package.json"), "utf8"));
  } catch {
    missing.push(`${name} (not installed)`);
    continue;
  }
  let text = await licenceTextFor(name);
  let borrowedFrom = null;
  if (!text && BORROWED_TEXT[name]) {
    borrowedFrom = BORROWED_TEXT[name];
    text = await licenceTextFor(borrowedFrom);
  }
  if (!text) {
    // Named rather than skipped: a dependency whose licence cannot be found is
    // a thing to go and resolve, not a thing to quietly omit from the notices.
    missing.push(`${name}@${meta.version} — ${meta.license ?? "licence unknown"}`);
    continue;
  }
  sections.push(
    `## ${name} ${meta.version}\n\n` +
      `${meta.license ?? "See licence text"}${meta.homepage ? ` · ${meta.homepage}` : ""}\n\n` +
      (borrowedFrom
        ? `_This package ships no licence file. The text below is the same licence, taken from\n` +
          `\`${borrowedFrom}\`, published from the same repository._\n\n`
        : "") +
      "```\n" + text + "\n```\n",
  );
}

const notices =
  `# Third-party notices\n\n` +
  `Braveli includes the following third-party software. Each is used under its own\n` +
  `licence, reproduced in full below. Braveli itself is not open source; see LICENSE.\n\n` +
  `Generated by \`scripts/generate-notices.mjs\` — do not edit by hand.\n\n` +
  `---\n\n` +
  sections.join("\n---\n\n");

await writeFile(path.join(root, "THIRD_PARTY_NOTICES.md"), notices);

console.log(`Wrote THIRD_PARTY_NOTICES.md — ${sections.length} packages`);
if (missing.length) {
  console.log(`\nNo licence file found for ${missing.length}; resolve these by hand:`);
  for (const entry of missing) console.log(`  - ${entry}`);
}
