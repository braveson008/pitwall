import { describe, expect, it } from "vitest";
import { commitMessage, composeRequest, requestTitle, stripWatermarks, type RequestDraftInput } from "./requestDraft";

const task = (over: Partial<RequestDraftInput["task"]> = {}): RequestDraftInput["task"] => ({
  identifier: "shop-1936",
  title: "[Front][Dataset/AoO] Show the full path of a file",
  description: "<p>Users cannot tell which folder a file is in.</p><p>See the thread.</p>",
  source: { kind: "mcp", name: "atlassian", url: "https://acme.atlassian.net/browse/SHOP-1936" },
  ...over,
});

describe("requestTitle", () => {
  it("leads with the ticket key so trackers link it", () => {
    expect(requestTitle(task())).toBe("SHOP-1936: [Front][Dataset/AoO] Show the full path of a file");
  });

  it("does not repeat a key the title already has", () => {
    expect(requestTitle(task({ title: "SHOP-1936 Show the full path" }))).toBe("SHOP-1936: Show the full path");
    expect(requestTitle(task({ title: "[SHOP-1936] Show the full path" }))).toBe("SHOP-1936: Show the full path");
  });

  it("is just the title without a key", () => {
    expect(requestTitle(task({ identifier: "" }))).toBe("[Front][Dataset/AoO] Show the full path of a file");
  });
});

describe("stripWatermarks", () => {
  it("removes every line that only says an AI or agent wrote it", () => {
    const text = [
      "Show the full path in the tooltip",
      "",
      "🤖 Generated with [Claude Code](https://claude.com/claude-code)",
      "Co-Authored-By: Claude Opus <noreply@anthropic.com>",
      "Generated by Codex",
      "Signed-off-by: A Person <a@b.c>",
    ].join("\n");
    expect(stripWatermarks(text)).toBe("Show the full path in the tooltip\n\nSigned-off-by: A Person <a@b.c>");
  });

  it("keeps ordinary sentences that merely mention a tool", () => {
    expect(stripWatermarks("Generated the thumbnails with sharp")).toBe("Generated the thumbnails with sharp");
  });
});

describe("composeRequest", () => {
  it("writes Summary, Changes, How to test and Ticket from what is known", () => {
    const { title, body } = composeRequest({
      task: task({
        completionSummary: {
          what: "Shows the folder path under each file name in the dataset view.",
          how: "- Added a path line to FileRow\n- Truncates from the left so the file name stays visible",
          components: [],
          source: "agent",
          reportedAt: "",
        },
      }),
      commits: ["feat: show path", "Co-Authored-By: Claude <noreply@anthropic.com>"],
      files: ["src/FileRow.tsx", "src/FileRow.test.tsx"],
      checks: {
        ok: true,
        ranAt: "",
        checks: [
          { name: "Tests", command: "npm test", ok: true, output: "", skipped: false, durationMs: 1 },
          { name: "Lint", command: "npm run lint", ok: true, output: "", skipped: true, durationMs: 0 },
        ],
      },
    });
    expect(title).toBe("SHOP-1936: [Front][Dataset/AoO] Show the full path of a file");
    expect(body).toBe([
      "## Summary",
      "",
      "Shows the folder path under each file name in the dataset view.",
      "",
      "## Changes",
      "",
      "- Added a path line to FileRow",
      "- Truncates from the left so the file name stays visible",
      "- Files: `src/FileRow.tsx`, `src/FileRow.test.tsx`",
      "",
      "## How to test",
      "",
      "- `npm test` — passed",
      "",
      "## Ticket",
      "",
      "[SHOP-1936](https://acme.atlassian.net/browse/SHOP-1936)",
    ].join("\n"));
  });

  it("falls back to the ticket and the commits, never to Pitwall's own bookkeeping", () => {
    const { body } = composeRequest({
      task: task({
        completionSummary: {
          what: "The agent completed work for shop-1936.",
          how: "Work was performed in /Users/someone/Library/Application Support/braveli/worktrees/x",
          components: [],
          source: "derived",
          reportedAt: "",
        },
      }),
      commits: ["Show the full path in the tooltip", "Show the full path in the tooltip", "🤖 Generated with Claude Code"],
      files: [],
    });
    expect(body).toContain("Users cannot tell which folder a file is in.");
    expect(body).toContain("- Show the full path in the tooltip");
    expect(body).not.toMatch(/agent|braveli|\/Users\/|claude|generated/i);
    expect(body).toContain("- [ ] Checked locally");
  });

  it("fills the repository's template instead of its own layout", () => {
    const template = [
      "## What does this MR do?",
      "",
      "<!-- Describe the change -->",
      "",
      "## How to test",
      "",
      "## Checklist",
      "",
      "- [ ] Tests added",
      "- [ ] Docs updated",
      "",
      "## Related issues",
      "",
      "Closes #",
    ].join("\n");
    const { body } = composeRequest({ task: task(), commits: ["Show path"], files: [], template });
    expect(body).toContain("## What does this MR do?\n\nUsers cannot tell which folder a file is in.");
    expect(body).not.toContain("<!--");
    expect(body).toContain("## How to test\n\n- [ ] Checked locally");
    // A checklist the team expects a person to tick stays exactly as written.
    expect(body).toContain("## Checklist\n\n- [ ] Tests added\n- [ ] Docs updated");
    expect(body).toContain("## Related issues\n\n[SHOP-1936](https://acme.atlassian.net/browse/SHOP-1936)");
  });
});

describe("composeRequest with prose written from the change", () => {
  it("never uses Pitwall's own placeholder as the summary", () => {
    const { body } = composeRequest({ task: task({ description: "Imported from connected work." }), commits: [], files: [] });
    expect(body).not.toMatch(/imported from connected work/i);
    expect(body).toMatch(/^## Summary\n\nSHOP-1936: /);
  });

  it("leads with what the writer read in the change, and keeps it clean", () => {
    const { body } = composeRequest({
      task: task(),
      commits: [],
      files: ["src/Dataset.tsx", "src/getLastImportInfo.ts"],
      written: {
        summary: "Shows the dataset's last modification time in the viewer's local time zone instead of UTC.",
        changes: ["Format the timestamp with the browser's locale", "- Add getLastImportInfo helper"],
        testing: ["Open a dataset and compare the time with the import log", "[ ] Switch the OS time zone and reload"],
      },
    });
    expect(body).toContain("## Summary\n\nShows the dataset's last modification time in the viewer's local time zone instead of UTC.");
    expect(body).toContain("- Format the timestamp with the browser's locale\n- Add getLastImportInfo helper\n- Files: `src/Dataset.tsx`, `src/getLastImportInfo.ts`");
    expect(body).toContain("- [ ] Open a dataset and compare the time with the import log\n- [ ] Switch the OS time zone and reload");
  });
});

describe("commitMessage", () => {
  it("is a conventional subject with the key, then why", () => {
    expect(commitMessage(task(), { summary: "", changes: [], testing: [], commitSubject: "Show last modification in local time.", commitBody: "Users read UTC as their own time." })).toBe(
      "SHOP-1936: Show last modification in local time\n\nUsers read UTC as their own time.",
    );
  });

  it("falls back to the title without its bracket tags, and drops trailers", () => {
    expect(commitMessage(task())).toBe("SHOP-1936: Show the full path of a file");
    expect(commitMessage(task(), { summary: "", changes: [], testing: [], commitSubject: "SHOP-1936 Fix it", commitBody: "Co-Authored-By: Claude <noreply@anthropic.com>" })).toBe(
      "SHOP-1936: Fix it",
    );
  });
});
